"""Draw the cracked eggshell print that surrounds the P1 screen.

The original Tamagotchi has a print of a cracked eggshell on the plastic
around the display. It is part of the moulding, not a sticker, so it sits
flat on the body and follows the curve of the egg.

Run this from the repository root to write `shell/src/eggshell.svg`:

    python3 shell/tools/eggshell.py

The output is deterministic, so a rerun only produces a diff when the
generator itself changes.
"""

import math
import random

# The device, in the same units the shell uses: CSS pixels.
WIDTH = 276
HEIGHT = 360

# The glass, in device coordinates.
GLASS_X, GLASS_Y = 64, 131
GLASS_W, GLASS_H = 148, 150

# How far a crack may wander before it is clipped.
MARGIN = 8

# The colour of the print. It is darker than the plastic and slightly warm.
INK = "#7d6a62"
INK_OPACITY = 0.42
STROKE = 1.0

# Angles are measured in radians with the y axis pointing down, which is how
# SVG works. Zero points right, a quarter turn points down.
LEFT = math.pi
UP = -math.pi / 2
RIGHT = 0.0
DOWN = math.pi / 2

SEED = 11

# Each corner of the glass sends three cracks outward, spread around the
# direction that points away from the glass.
CORNERS = [
    (GLASS_X, GLASS_Y, [1.05 * math.pi, 1.25 * math.pi, 1.42 * math.pi]),
    (GLASS_X + GLASS_W, GLASS_Y, [1.58 * math.pi, 1.75 * math.pi, 1.95 * math.pi]),
    (GLASS_X, GLASS_Y + GLASS_H, [0.55 * math.pi, 0.75 * math.pi, 0.92 * math.pi]),
    (
        GLASS_X + GLASS_W,
        GLASS_Y + GLASS_H,
        [0.05 * math.pi, 0.25 * math.pi, 0.48 * math.pi],
    ),
]

# Points along the edges of the glass, each sending a pair of cracks out.
EDGES = [
    (GLASS_X, GLASS_Y + GLASS_H * 0.30, LEFT),
    (GLASS_X, GLASS_Y + GLASS_H * 0.66, LEFT),
    (GLASS_X + GLASS_W, GLASS_Y + GLASS_H * 0.34, RIGHT),
    (GLASS_X + GLASS_W, GLASS_Y + GLASS_H * 0.72, RIGHT),
    (GLASS_X + GLASS_W * 0.24, GLASS_Y, UP),
    (GLASS_X + GLASS_W * 0.60, GLASS_Y, UP),
    (GLASS_X + GLASS_W * 0.44, GLASS_Y + GLASS_H, DOWN),
    (GLASS_X + GLASS_W * 0.74, GLASS_Y + GLASS_H, DOWN),
]


def crack(rng, x, y, angle, length):
    """Return one cracked line as an SVG path, or None if it left the body."""
    points = [(x, y)]
    heading = angle
    steps = 3 + rng.randrange(3)
    for _ in range(steps):
        heading += rng.uniform(-0.42, 0.42)
        x += math.cos(heading) * (length / steps)
        y += math.sin(heading) * (length / steps)
        if not (MARGIN < x < WIDTH - MARGIN and MARGIN < y < HEIGHT - MARGIN):
            break
        points.append((x, y))
    if len(points) < 2:
        return None
    drawn = " L ".join(f"{px:.1f} {py:.1f}" for px, py in points)
    return f'    <path d="M {drawn}" />'


def build():
    rng = random.Random(SEED)
    paths = []

    for x, y, angles in CORNERS:
        for angle in angles:
            path = crack(rng, x, y, angle, rng.uniform(20, 44))
            if path:
                paths.append(path)

    for x, y, outward in EDGES:
        for offset in (rng.uniform(0.05, 0.38), -rng.uniform(0.05, 0.38)):
            path = crack(rng, x, y, outward + offset, rng.uniform(13, 30))
            if path:
                paths.append(path)

    body = "\n".join(paths)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}"\n'
        f'     width="{WIDTH}" height="{HEIGHT}" aria-hidden="true">\n'
        f"  <!-- Generated by shell/tools/eggshell.py. Do not edit by hand. -->\n"
        f'  <g fill="none" stroke="{INK}" stroke-opacity="{INK_OPACITY}"\n'
        f'     stroke-width="{STROKE}" stroke-linecap="round">\n'
        f"{body}\n"
        f"  </g>\n"
        f"</svg>\n"
    )


def main():
    import pathlib

    root = pathlib.Path(__file__).resolve().parents[2]
    target = root / "shell" / "src" / "eggshell.svg"
    target.write_text(build())
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
