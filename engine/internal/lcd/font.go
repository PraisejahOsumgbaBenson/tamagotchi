package lcd

// The built in font. Each glyph is 3 by 5 pixels, the leftmost pixel of a row
// being the least significant bit.
//
// A 32 by 16 display cannot carry much text, so the font is small on purpose.
// It is the same size the original hardware uses for its numbers, which is
// the whole reason the meter screens fit.
const (
	glyphWidth  = 3
	glyphHeight = 5
)

