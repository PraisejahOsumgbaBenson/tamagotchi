// sprite builds a bitmap from rows of text, where '#' is an on pixel and
// anything else is off.
//
// The artwork is kept as text rather than packed bits so that it can be
// read and edited. The display is 32 by 16 pixels, so every row here is
// sixteen characters wide.
func sprite(rows ...string) lcd.Sprite {
	width := 0
	for _, r := range rows {
		if len(r) > width {
			width = len(r)
		}
	}

	out := lcd.Sprite{
		Width:  width,
		Height: len(rows),
		Rows:   make([]uint32, len(rows)),
	}

	for y, row := range rows {
		for x := 0; x < len(row); x++ {
			if row[x] == '#' {
				out.Rows[y] |= 1 << uint(x)
			}
		}
	}

	return out
}

// mustSprite is sprite with the row lengths checked, for use at package
// initialisation.
func mustSprite(rows ...string) lcd.Sprite {
	sp := sprite(rows...)
	for _, r := range rows {
		if len(r) != 16 {
			panic(fmt.Sprintf("pet: sprite row %q is %d wide, want 16", r, len(r)))
		}
	}
	return sp
}

